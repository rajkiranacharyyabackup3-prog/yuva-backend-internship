CREATE TABLE blog_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_blog_users_username UNIQUE (username),
    CONSTRAINT uq_blog_users_email UNIQUE (email),
    CONSTRAINT ck_blog_users_username CHECK (CHAR_LENGTH(TRIM(username)) BETWEEN 3 AND 50),
    CONSTRAINT ck_blog_users_email CHECK (CHAR_LENGTH(TRIM(email)) BETWEEN 3 AND 254),
    CONSTRAINT ck_blog_users_password_hash CHECK (CHAR_LENGTH(password_hash) >= 20)
);

CREATE TABLE posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(160) NOT NULL,
    content TEXT NOT NULL,
    author_id BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_posts_author FOREIGN KEY (author_id) REFERENCES blog_users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_posts_title CHECK (CHAR_LENGTH(TRIM(title)) BETWEEN 1 AND 160),
    CONSTRAINT ck_posts_content CHECK (CHAR_LENGTH(TRIM(content)) BETWEEN 1 AND 10000)
);

CREATE INDEX idx_posts_created_at ON posts (created_at DESC);
CREATE INDEX idx_posts_author_id ON posts (author_id);

CREATE TABLE comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL,
    author_id BIGINT NOT NULL,
    content VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_comments_post FOREIGN KEY (post_id) REFERENCES posts (id) ON DELETE CASCADE,
    CONSTRAINT fk_comments_author FOREIGN KEY (author_id) REFERENCES blog_users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_comments_content CHECK (CHAR_LENGTH(TRIM(content)) BETWEEN 1 AND 2000)
);

CREATE INDEX idx_comments_post_created ON comments (post_id, created_at);
CREATE INDEX idx_comments_author_id ON comments (author_id);
